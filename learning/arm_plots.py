"""
Figures for the arm's learned sampler.

    python -m learning.arm_plots --dof 4

Reads only saved results and the saved model; never re-runs the evaluation.

    results/arm/arm<dof>_convergence.png   success rate and cost vs iteration
    results/arm/arm<dof>_proposals.png     what the network proposes vs uniform

Uses the same method colours as the 2-D figures (learning/plots.py): aqua =
uniform sampling, violet = learned, dashed = "+ informed".
"""

import argparse
import json
import math
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
from matplotlib.lines import Line2D

from arm import random_arm_problem
from arm.plot import draw_arm, draw_world
from viz.charts import INK_PRIMARY, INK_SECONDARY, SURFACE, _new_figure, _save, _style_axes
from viz.plot import GOAL_COLOR, START_COLOR

from .arm_data import SEED_BASE, occupancy_image
from .arm_evaluate import COST_CAP, METHODS, OUT_DIR
from .arm_model import load_model
from .evaluate import best_known, cost_at, load_rows
from .plots import LEARNED, METHOD_STYLE

STYLE = {m: METHOD_STYLE[m] for m in METHODS}
STYLE["RRT* + informed"] = dict(STYLE["RRT* + informed"], label="Informed RRT*")


def chart_convergence(rows, dof, max_iters, out_path):
    solvable = {r["problem"] for r in rows if r["success"]}
    rows = [r for r in rows if r["problem"] in solvable]
    ref = {p: c for (_, p), c in best_known(rows).items()}
    grid = np.unique(np.round(np.geomspace(20, max_iters, 120)).astype(int))

    fig = _new_figure(11.0, 4.9)
    fig.text(0.015, 0.975, "Arm with %d joints: learned sampling vs RRT* and Informed RRT*" % dof,
             fontsize=13, fontweight="bold", color=INK_PRIMARY, va="top")
    fig.text(0.015, 0.905,
             "%d held-out worlds with a known solution, 3 runs each. Left: share of runs that have "
             "found a path. Right: mean path cost relative to the\nbest known (1.0), counting a run "
             "with no path yet as %.0f, so it rewards both finding a path and finding a short one."
             % (len(solvable), COST_CAP), fontsize=9.3, color=INK_SECONDARY, va="top", linespacing=1.45)
    ax1 = fig.add_axes([0.07, 0.13, 0.38, 0.56])
    ax2 = fig.add_axes([0.56, 0.13, 0.38, 0.56])
    for m in METHODS:
        rs = [r for r in rows if r["method"] == m]
        st = STYLE[m]
        succ = [np.mean([math.isfinite(cost_at(r["history"], k)) for r in rs]) for k in grid]
        cost = []
        for k in grid:
            v = [cost_at(r["history"], k) / ref[r["problem"]] for r in rs]
            cost.append(np.mean([min(x, COST_CAP) if math.isfinite(x) else COST_CAP for x in v]))
        ax1.plot(grid, np.array(succ) * 100, color=st["color"], linestyle=st["linestyle"], linewidth=2)
        ax2.plot(grid, cost, color=st["color"], linestyle=st["linestyle"], linewidth=2)
    for ax, ylab in ((ax1, "Runs with a path (%)"), (ax2, "Mean normalised cost")):
        ax.set_xscale("log")
        ax.set_xlim(grid[0], grid[-1])
        _style_axes(ax)
        ax.set_xlabel("Iterations (log scale)", fontsize=9, color=INK_SECONDARY)
        ax.set_ylabel(ylab, fontsize=9, color=INK_SECONDARY)
    handles = [Line2D([], [], color=STYLE[m]["color"], linestyle=STYLE[m]["linestyle"],
                      linewidth=2, label=STYLE[m]["label"]) for m in METHODS]
    leg = fig.legend(handles=handles, loc="upper left", bbox_to_anchor=(0.012, 0.80),
                     ncol=4, frameon=False, fontsize=9, handlelength=2.6)
    for t in leg.get_texts():
        t.set_color(INK_SECONDARY)
    return _save(fig, out_path)


def figure_proposals(dof, model_path, out_path, world=0, n=40):
    """Network proposals vs uniform random poses, drawn in the world."""
    env = random_arm_problem(dof, SEED_BASE["test"] + world)
    model, _ = load_model(model_path)
    gen = torch.Generator().manual_seed(0)
    q = model.generate(torch.from_numpy(occupancy_image(env, model.grid).astype(np.float32)),
                       torch.tensor(env.start, dtype=torch.float32),
                       torch.tensor(env.goal, dtype=torch.float32), n, generator=gen).numpy()
    uni = np.random.default_rng(0).uniform(-math.pi, math.pi, (n, dof))

    fig = plt.figure(figsize=(11.0, 6.0), dpi=150, facecolor=SURFACE)
    fig.text(0.015, 0.975, "What the network proposes for an unseen world", fontsize=13,
             fontweight="bold", color=INK_PRIMARY, va="top")
    fig.text(0.015, 0.915, "%d poses each. Green = start pose, red = goal pose. Left: drawn "
             "uniformly at random (what RRT* samples). Right: generated by the trained network "
             "for this world, start and goal." % n, fontsize=9.3, color=INK_SECONDARY, va="top")
    for k, (title, Q, color) in enumerate((("Uniform random poses", uni, "#1baf7a"),
                                           ("Network proposals", q, LEARNED))):
        ax = fig.add_axes([0.02 + 0.49 * k, 0.03, 0.46, 0.80])
        draw_world(ax, env)
        for pose in Q:
            draw_arm(ax, env, pose, color, alpha=0.25, linewidth=2.2, zorder=3)
        draw_arm(ax, env, env.start, START_COLOR, zorder=5)
        draw_arm(ax, env, env.goal, GOAL_COLOR, zorder=5)
        ax.set_title(title, fontsize=10, loc="left", color=INK_PRIMARY)
    fig.savefig(out_path, facecolor=SURFACE)
    plt.close(fig)
    return out_path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dof", type=int, default=4)
    ap.add_argument("--world", type=int, default=0, help="test world for the proposals figure")
    args = ap.parse_args()
    stem = os.path.join(OUT_DIR, "eval_arm%d" % args.dof)
    meta = json.load(open(stem + "_meta.json"))
    rows = load_rows(stem + "_raw.csv", stem + "_histories.json")
    print("  ->", chart_convergence(rows, args.dof, meta["max_iters"],
                                    os.path.join(OUT_DIR, "arm%d_convergence.png" % args.dof)))
    print("  ->", figure_proposals(args.dof, meta["model"],
                                   os.path.join(OUT_DIR, "arm%d_proposals.png" % args.dof),
                                   world=args.world))


if __name__ == "__main__":
    main()
